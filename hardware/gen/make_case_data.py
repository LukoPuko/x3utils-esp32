"""Write hardware/case/board_data.scad from circuit.py.

The case model reads every connector / button / LED position from this file,
so moving a part on the PCB moves its cut-out in the case as well.

SCAD coordinates: X = board x, Y = BOARD_H - board y (board's port end at
Y = 0, antenna end at Y = BOARD_H), Z = up. Units mm.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import circuit as C  # noqa: E402

OUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "case", "board_data.scad"))


def pos(ref):
    p = next(p for p in C.PARTS if p.ref == ref)
    return p.pcb


def Y(y):
    return round(C.BOARD_H - y, 3)


def main():
    j1 = pos("J1")
    sw1 = pos("SW1")
    j2 = pos("J2")
    j3 = pos("J3")
    lines = [
        "// GENERATED by hardware/gen/make_case_data.py from circuit.py — do not edit.",
        "BOARD_W = %s;" % C.BOARD_W,
        "BOARD_H = %s;" % C.BOARD_H,
        "BOARD_R = %s;" % C.CORNER_R,
        "PCB_T = 1.6;",
        # ESP32 module body (18 x 25.5) and its antenna end
        "U1_XY = [%s, %s];" % (C.U1_X, Y(C.U1_Y)),
        "ANTENNA_Y = %s;  // above this Y: antenna, keep metal away" % Y(C.U1_Y - 6.75),
        # USB-C on the left edge (KiCad rot 270: receptacle opening faces -X)
        "USB_Y = %s;" % Y(j1[1]),
        "USB_FRONT_X = %s;" % round(j1[0] - 3.65, 3),
        # slide switch on the right edge; lever reaches past the board edge
        "SW1_Y = %s;" % Y(sw1[1]),
        "SW1_LEVER_X = %s;" % round(sw1[0] + 4.25, 3),
        # JST-PH battery socket (opening faces the port end, -Y)
        "J2_XY = [%s, %s];" % (j2[0], Y(j2[1])),
        "J2_FRONT_Y = %s;" % Y(j2[1] + 4.4),
        # right-angle SWD header: pin 1 (3V3) at the right, pins run to -X
        "J3_PIN1_X = %s;" % j3[0],
        "J3_ROW_Y = %s;" % Y(j3[1]),
        "J3_TIP_Y = %s;  // pin tips (10.04 mm from the pin row)" % Y(j3[1] + 10.04),
        "J3_PITCH = 2.54;",
        'J3_LABELS = ["3V3", "DIO", "CLK", "RST", "GND"];',
        "SW2_XY = [%s, %s];  // RESET" % (pos("SW2")[0], Y(pos("SW2")[1])),
        "SW3_XY = [%s, %s];  // BOOT" % (pos("SW3")[0], Y(pos("SW3")[1])),
        "LED_STAT_XY = [%s, %s];" % (pos("D4")[0], Y(pos("D4")[1])),
        "LED_CHG_XY = [%s, %s];  // red + green, one window" % (
            round((pos("D2")[0] + pos("D3")[0]) / 2, 3), Y((pos("D2")[1] + pos("D3")[1]) / 2)),
        # free spots on the board where lid posts may press the PCB down
        "LID_POSTS = [%s];" % ", ".join("[%s, %s]" % (x, Y(y)) for x, y in C.CASE_POSTS),
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("case data ->", OUT)


if __name__ == "__main__":
    main()
